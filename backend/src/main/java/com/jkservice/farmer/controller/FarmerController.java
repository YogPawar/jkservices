package com.jkservice.farmer.controller;

import com.jkservice.common.response.ApiResponse;
import com.jkservice.farmer.dto.CreateFarmerRequest;
import com.jkservice.farmer.dto.FarmerResponse;
import com.jkservice.farmer.dto.UpdateFarmerRequest;
import com.jkservice.farmer.service.FarmerService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import java.net.URI;
import java.util.List;
import lombok.RequiredArgsConstructor;
import org.springframework.http.ProblemDetail;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.servlet.support.ServletUriComponentsBuilder;

@RestController
@RequestMapping("/api/v1/businesses/{businessId}/farmers")
@RequiredArgsConstructor
@Tag(
    name = "Farmer Management",
    description =
        "APIs for creating, retrieving, updating and deactivating farmers within a business")
public class FarmerController {

  private final FarmerService farmerService;

  @PostMapping
  @Operation(
      summary = "Create a farmer",
      description =
          "Creates a new farmer under the specified business. "
              + "The farmer code is generated by the backend.")
  @ApiResponses({
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "201",
        description = "Farmer created successfully",
        content = @Content(schema = @Schema(implementation = ApiResponse.class))),
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "400",
        description = "Invalid request or inactive business",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class))),
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "404",
        description = "Business not found",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class))),
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "409",
        description = "Duplicate farmer resource",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
  })
  public ResponseEntity<ApiResponse<FarmerResponse>> createFarmer(
      @Parameter(description = "Unique business ID", example = "1") @PathVariable Long businessId,
      @Valid
          @org.springframework.web.bind.annotation.RequestBody
          @io.swagger.v3.oas.annotations.parameters.RequestBody(
              description = "Farmer details required for creation",
              required = true)
          CreateFarmerRequest request) {

    FarmerResponse farmerResponse = farmerService.createFarmer(businessId, request);

    URI location =
        ServletUriComponentsBuilder.fromCurrentRequest()
            .path("/{farmerId}")
            .buildAndExpand(farmerResponse.id())
            .toUri();

    return ResponseEntity.created(location)
        .body(ApiResponse.success("Farmer created successfully", farmerResponse));
  }

  @GetMapping
  @Operation(
      summary = "Get all farmers",
      description = "Retrieves all farmers belonging to the specified business.")
  @ApiResponses({
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "200",
        description = "Farmers retrieved successfully",
        content = @Content(schema = @Schema(implementation = ApiResponse.class))),
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "404",
        description = "Business not found",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
  })
  public ResponseEntity<ApiResponse<List<FarmerResponse>>> getFarmers(
      @Parameter(description = "Unique business ID", example = "1") @PathVariable Long businessId) {

    List<FarmerResponse> farmers = farmerService.getFarmers(businessId);

    return ResponseEntity.ok(ApiResponse.success("Farmers retrieved successfully", farmers));
  }

  @GetMapping("/{farmerId}")
  @Operation(
      summary = "Get farmer by ID",
      description = "Retrieves a farmer using the farmer ID, scoped to the specified business.")
  @ApiResponses({
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "200",
        description = "Farmer retrieved successfully",
        content = @Content(schema = @Schema(implementation = ApiResponse.class))),
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "404",
        description = "Farmer not found in the specified business",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
  })
  public ResponseEntity<ApiResponse<FarmerResponse>> getFarmer(
      @Parameter(description = "Unique business ID", example = "1") @PathVariable Long businessId,
      @Parameter(description = "Unique farmer ID", example = "100") @PathVariable Long farmerId) {

    FarmerResponse farmer = farmerService.getFarmer(businessId, farmerId);

    return ResponseEntity.ok(ApiResponse.success("Farmer retrieved successfully", farmer));
  }

  @PutMapping("/{farmerId}")
  @Operation(
      summary = "Update farmer",
      description = "Updates the farmer details. The farmer must belong to the specified business.")
  @ApiResponses({
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "200",
        description = "Farmer updated successfully",
        content = @Content(schema = @Schema(implementation = ApiResponse.class))),
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "400",
        description = "Invalid request or inactive business",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class))),
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "404",
        description = "Farmer or business not found",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
  })
  public ResponseEntity<ApiResponse<FarmerResponse>> updateFarmer(
      @Parameter(description = "Unique business ID", example = "1") @PathVariable Long businessId,
      @Parameter(description = "Unique farmer ID", example = "100") @PathVariable Long farmerId,
      @Valid
          @org.springframework.web.bind.annotation.RequestBody
          @io.swagger.v3.oas.annotations.parameters.RequestBody(
              description = "Updated farmer details",
              required = true)
          UpdateFarmerRequest request) {

    FarmerResponse farmer = farmerService.updateFarmer(businessId, farmerId, request);

    return ResponseEntity.ok(ApiResponse.success("Farmer updated successfully", farmer));
  }

  @DeleteMapping("/{farmerId}")
  @Operation(
      summary = "Deactivate farmer",
      description =
          "Soft-deactivates a farmer by setting the active status to false. "
              + "The farmer record is retained in the database.")
  @ApiResponses({
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "200",
        description = "Farmer deactivated successfully",
        content = @Content(schema = @Schema(implementation = ApiResponse.class))),
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "404",
        description = "Farmer or business not found",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class))),
    @io.swagger.v3.oas.annotations.responses.ApiResponse(
        responseCode = "400",
        description = "Business is inactive",
        content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
  })
  public ResponseEntity<ApiResponse<Void>> deactivateFarmer(
      @Parameter(description = "Unique business ID", example = "1") @PathVariable Long businessId,
      @Parameter(description = "Unique farmer ID", example = "100") @PathVariable Long farmerId) {

    farmerService.deactivateFarmer(businessId, farmerId);

    return ResponseEntity.ok(ApiResponse.success("Farmer deactivated successfully"));
  }
}
